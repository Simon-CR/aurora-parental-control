#!/usr/bin/env python3
"""Sync per-title PeerPressure SideLoading INI configs from Aurora's content.db."""

from __future__ import annotations

import argparse
import ftplib
import io
import os
import sqlite3
import tempfile
from dataclasses import dataclass


SIDELOAD_DIR = "/Hdd1/PeerPressure/SideLoading"
CONTENT_DB_PATH = "/Game/Data/Databases/content.db"
PROTECTED_FILES = {"config.ini", "sideload.ini"}


@dataclass(frozen=True)
class TitleEntry:
    title_id_hex: str
    title_name: str


def connect_ftp(host: str, port: int, user: str, password: str, timeout: int = 15) -> ftplib.FTP:
    ftp = ftplib.FTP()
    ftp.connect(host, port, timeout=timeout)
    ftp.login(user, password)
    ftp.set_pasv(True)
    return ftp


def fetch_bytes(ftp: ftplib.FTP, remote_path: str) -> bytes:
    buf = io.BytesIO()
    ftp.retrbinary(f"RETR {remote_path}", buf.write)
    return buf.getvalue()


def list_files(ftp: ftplib.FTP, directory: str) -> dict[str, int]:
    entries: dict[str, int] = {}
    lines: list[str] = []
    ftp.retrlines(f"LIST {directory}", lines.append)
    for line in lines:
        parts = line.split(maxsplit=8)
        if len(parts) < 9:
            continue
        name = parts[8].strip()
        if name in {".", ".."} or parts[0].startswith("d"):
            continue
        try:
            entries[name.lower()] = int(parts[4])
        except ValueError:
            entries[name.lower()] = 0
    return entries


def read_unique_titles(db_bytes: bytes) -> list[TitleEntry]:
    fd, tmp_path = tempfile.mkstemp(suffix=".db")
    os.close(fd)
    try:
        with open(tmp_path, "wb") as f:
            f.write(db_bytes)
        con = sqlite3.connect(tmp_path)
        try:
            rows = con.execute(
                "SELECT TitleId, MIN(TitleName) FROM ContentItems "
                "WHERE TitleId IS NOT NULL AND TitleId != 0 "
                "GROUP BY TitleId ORDER BY TitleId"
            ).fetchall()
        finally:
            con.close()
    finally:
        if os.path.exists(tmp_path):
            os.remove(tmp_path)

    titles: list[TitleEntry] = []
    for raw_id, name in rows:
        hex_id = f"{int(raw_id) & 0xFFFFFFFF:08X}"
        if hex_id == "00000000":
            continue
        titles.append(TitleEntry(title_id_hex=hex_id, title_name=name or hex_id))
    return titles


def render_ini(title: TitleEntry, dll_filename: str) -> str:
    return (
        f"; Auto-generated by aurora-parental-control sideload_sync.py ({title.title_name})\r\n"
        f"[DllConfig]\r\n"
        f"TitleID = 0x{title.title_id_hex}\r\n"
        f'FileName = "{dll_filename}"\r\n'
    )


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate PeerPressure SideLoading <TitleID>.ini files from Aurora content.db.")
    parser.add_argument("--host", required=True, help="Xbox 360 FTP host/IP")
    parser.add_argument("--port", type=int, default=21, help="FTP port (default: 21)")
    parser.add_argument("--user", default="xboxftp", help="FTP username (default: xboxftp)")
    parser.add_argument("--password", default="xboxftp", help="FTP password (default: xboxftp)")
    parser.add_argument("--dll-name", default="screentime_dll.xex", help="DLL filename relative to SideLoading/")
    parser.add_argument("--apply", action="store_true", help="Write <TITLEID>.ini files via FTP (default is dry-run)")
    args = parser.parse_args()

    ftp = connect_ftp(args.host, args.port, args.user, args.password)
    try:
        db_bytes = fetch_bytes(ftp, CONTENT_DB_PATH)
        titles = read_unique_titles(db_bytes)
        existing = list_files(ftp, SIDELOAD_DIR)

        would_create = 0
        would_skip_existing = 0
        written = 0

        for title in titles:
            ini_name = f"{title.title_id_hex}.ini"
            if ini_name.lower() in PROTECTED_FILES:
                continue
            if ini_name.lower() in existing:
                would_skip_existing += 1
                continue
            would_create += 1
            if args.apply:
                payload = render_ini(title, args.dll_name).encode("utf-8")
                ftp.storbinary(f"STOR {SIDELOAD_DIR}/{ini_name}", io.BytesIO(payload))
                written += 1

        mode = "APPLY" if args.apply else "DRY-RUN"
        print(f"[{mode}] Unique titles in content.db: {len(titles)}")
        print(f"[{mode}] Already present in {SIDELOAD_DIR}: {would_skip_existing}")
        print(f"[{mode}] Missing <TITLEID>.ini files: {would_create}")
        if args.apply:
            print(f"[{mode}] Uploaded new INI files: {written}")
        else:
            print("[DRY-RUN] Re-run with --apply to write missing INI files.")
    finally:
        try:
            ftp.quit()
        except Exception:
            pass
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
